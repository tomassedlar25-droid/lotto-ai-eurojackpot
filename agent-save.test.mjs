import assert from 'node:assert/strict';
import {makeAgentSavedSet} from './agent-save.mjs';
const draws=[{date:'2026-10-09',main:[18,38,41,43,46],euro:[7,10]}];
const config={strategy:'hybridx',count:2,pool:12,filter:true,maxOverlap:2,manualExclude:[],fixedEuro:[]};
const tickets=[{main:[10,19,25,34,35],euro:[1,4]},{main:[12,25,27,34,37],euro:[3,5]}];
const inputs={draws,config,tickets,asOf:'2026-10-09',createdAt:'2026-10-12T08:00:00Z'};
const made=makeAgentSavedSet(inputs);
assert.equal(made.duplicate,false);
assert.equal(made.record.asOf,'2026-10-09');
assert.equal(made.record.source,'six-agents');
assert.equal(made.record.tickets.length,2);
assert.equal(makeAgentSavedSet({...inputs,existing:[made.record]}).duplicate,true);
assert.throws(()=>makeAgentSavedSet({...inputs,asOf:'2026-10-06'}),/Archiv se změnil/);
assert.throws(()=>makeAgentSavedSet({...inputs,tickets:[...tickets,{main:[1,2,3,4,5],euro:[1,2]}]}),/počet/);
assert.throws(()=>makeAgentSavedSet({...inputs,tickets:[tickets[0],tickets[0]]}),/Duplicitní/);
assert.throws(()=>makeAgentSavedSet({...inputs,tickets:[{main:[1,1,2,3,4],euro:[1,4]},tickets[1]]}),/Neplatný/);
assert.throws(()=>makeAgentSavedSet({...inputs,tickets:[{main:[1,2,3,4,5],euro:[1,13]},tickets[1]]}),/Neplatný/);
tickets[0].main[0]=99;
assert.equal(made.record.tickets[0].main.includes(99),false);
console.log('OK: agent 3.1 save, portfolio validation, archive date, duplicate protection, frozen ticket copies.');
